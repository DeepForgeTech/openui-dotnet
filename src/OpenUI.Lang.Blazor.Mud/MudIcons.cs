    /// <summary>The Material icon for an <c>Icon</c> component: its name, else its category, else a neutral dot. A missing icon is the neutral dot too.</summary>
    public static string Resolve(OuiComponent? icon) =>
        icon is null
            ? Neutral
            : DisplayValues.IconNames(icon).Select(name => Names.GetValueOrDefault(name)).FirstOrDefault(found => found is not null) ?? Neutral;
}
